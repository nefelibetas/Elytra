/** 方块名显示：原版中文优先，未知回退英文可读形式（minecraft: 前缀剥离）。 */
export function blockLabel(rawId: string): string {
	const id = rawId.startsWith("minecraft:") ? rawId.slice("minecraft:".length) : rawId;
	const zh = DICT[id];
	if (zh) return zh;
	// 英文回退：下划线 → 空格（id 大小写原样）
	return id.split("_").join(" ");
}

