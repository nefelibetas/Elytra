export function biomeLabel(rawId: string): string {
	const id = rawId.startsWith("minecraft:") ? rawId.slice("minecraft:".length) : rawId;
	const zh = BIOME_ZH[id];
	if (zh) return zh;
	return id.split("_").join(" ");
}
